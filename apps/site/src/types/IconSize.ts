// How finely a pixel icon is drawn: `coarse` on a 10 × 10 grid for big, blocky icons such as the option cards of the
// component pages, `small` on a 16 × 16 grid for icons next to text, `medium` on a 24 × 24 grid for mid-sized icons of
// lists and buttons, `normal` on a 32 × 32 grid for the large icons of cards and sections.
export type IconSize = 'coarse' | 'small' | 'medium' | 'normal';
